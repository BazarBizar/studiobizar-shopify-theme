/**
 * Writes the Liquid theme's half of the page builder's design value, from
 * scripts/lib/liquid-design.ts and lib/page-builder/design-style.ts:
 *
 *   - theme/snippets/sb-design.liquid       the design settings → CSS properties + data-sb-*
 *   - "Site style" in config/settings_schema.json   fonts and buttons for every page
 *   - theme/assets/sb-font-*.woff2           the ten fonts, the same Fontsource files
 *     + theme/snippets/sb-font-faces.liquid  the Next build uses (latin and latin-ext)
 *
 * The sections' own design settings are part of their schemas (`yarn liquid:schemas`).
 *
 *   yarn liquid:design           # write them
 *   yarn liquid:design --check   # fail if any is out of date (check:liquid runs this)
 */

import { copyFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { FONTS } from "../lib/page-builder/design-style";

import {
  DESIGN_SNIPPET,
  designSnippet,
  FONT_SNIPPET,
  FONT_STACK_SNIPPET,
  fontStackSnippet,
  siteStyleGroup,
} from "./lib/liquid-design";

const ROOT = resolve(__dirname, "..");
const THEME = resolve(ROOT, "theme");
const checkOnly = process.argv.includes("--check");
let stale = 0;

/** Same text with either line ending is the same file — git may check either out. */
const same = (a: string, b: string) => a.replace(/\r\n/g, "\n") === b.replace(/\r\n/g, "\n");

function write(path: string, text: string, what: string) {
  if (existsSync(path) && same(readFileSync(path, "utf8"), text)) return;
  if (checkOnly) {
    console.error(`✗ ${what} is out of date — run: yarn liquid:design`);
    stale += 1;
    return;
  }
  writeFileSync(path, text, "utf8");
  console.log(`wrote ${what}`);
}

/* The snippets */
write(resolve(THEME, "snippets", `${DESIGN_SNIPPET}.liquid`), designSnippet(), `snippets/${DESIGN_SNIPPET}.liquid`);
write(resolve(THEME, "snippets", `${FONT_STACK_SNIPPET}.liquid`), fontStackSnippet(), `snippets/${FONT_STACK_SNIPPET}.liquid`);

/* Site style, in config/settings_schema.json — placed after Typography, replaced in place after that. */
{
  const path = resolve(THEME, "config/settings_schema.json");
  const source = readFileSync(path, "utf8");
  const eol = source.includes("\r\n") ? "\r\n" : "\n";
  const text = source.replace(/\r\n/g, "\n");
  const group = JSON.stringify(siteStyleGroup(), null, 2)
    .split("\n")
    .map((line) => `  ${line}`)
    .join("\n");
  const existing = /\n {2}\{\n {4}"name": "Site style",[\s\S]*?\n {2}\}(?=,?\n)/;
  const next = existing.test(text)
    ? text.replace(existing, () => `\n${group}`)
    : text.replace(/\n\n {2}\{\n {4}"name": "Layout",/, () => `\n\n${group},\n\n  {\n    "name": "Layout",`);
  if (next === text && !existing.test(text)) throw new Error("settings_schema.json: no Layout group to place Site style before");
  JSON.parse(next); // still valid
  write(path, next.replace(/\n/g, eol), "config/settings_schema.json (Site style)");
}

/* Fonts: the latin and latin-ext files of each, as the Next build serves them. */
{
  const faces: string[] = [];
  for (const font of FONTS) {
    const css = readFileSync(resolve(ROOT, "node_modules/@fontsource-variable", font.id, "index.css"), "utf8");
    for (const subset of ["latin-ext", "latin"]) {
      const block = css.match(new RegExp(`/\\* ${font.id}-${subset}-wght-normal \\*/\\s*@font-face \\{([\\s\\S]*?)\\}`));
      if (!block) throw new Error(`${font.id}: no ${subset} face in @fontsource-variable/${font.id}`);
      const file = `${font.id}-${subset}-wght-normal.woff2`;
      const asset = `sb-font-${file}`;
      const source = resolve(ROOT, "node_modules/@fontsource-variable", font.id, "files", file);
      const target = resolve(THEME, "assets", asset);
      if (!existsSync(target) || !readFileSync(source).equals(readFileSync(target))) {
        if (checkOnly) {
          console.error(`✗ assets/${asset} is missing or out of date — run: yarn liquid:design`);
          stale += 1;
        } else {
          copyFileSync(source, target);
          console.log(`copied assets/${asset}`);
        }
      }
      const body = block[1]!.replace(/url\(\.\/files\/[^)]+\)/, `url({{ '${asset}' | asset_url }})`).trim();
      faces.push(`/* ${font.label}, ${subset} */\n@font-face {\n  ${body.split("\n").map((line) => line.trim()).join("\n  ")}\n}`);
    }
  }
  const snippet = `{% comment %}
  GENERATED by \`yarn liquid:design\` from the Fontsource packages — do not edit.

  The ten fonts the page builder offers (lib/page-builder/design-style.ts), the same
  files the Next build serves. A browser downloads a face only when a page uses it.
{% endcomment %}
<style>
${faces.join("\n")}
</style>
`;
  write(resolve(THEME, "snippets", `${FONT_SNIPPET}.liquid`), snippet, `snippets/${FONT_SNIPPET}.liquid`);
}

if (stale) process.exit(1);
if (checkOnly) console.log("✓ the theme's design snippet, Site style and fonts match the page builder");

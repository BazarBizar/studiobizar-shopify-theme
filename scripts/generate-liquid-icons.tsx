/**
 * Writes theme/snippets/sb-section-icon.liquid from the icons the Next sections
 * draw (`components/sections/section-icon.tsx`), so the theme shows the same
 * drawing for the same name — rendered from lucide itself, not copied by hand.
 *
 *   yarn liquid:icons           # rewrite the snippet
 *   yarn liquid:icons --check   # fail if the snippet is out of date (check:liquid runs this)
 *
 * Run it after changing the icon set in `lib/page-builder/icons.ts`.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { renderToStaticMarkup } from "react-dom/server";

import { ICONS } from "../components/sections/section-icon";
import { SECTION_ICONS } from "../lib/page-builder/icons";

const OUT = resolve(__dirname, "../theme/snippets/sb-section-icon.liquid");

export function iconSnippet(): string {
  const cases = SECTION_ICONS.filter((icon) => icon.value !== "none").map(({ value }) => {
    const Icon = ICONS[value as keyof typeof ICONS];
    const svg = renderToStaticMarkup(<Icon />);
    const inner = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
    return `  {%- when '${value}' -%}\n    ${inner}`;
  });

  return `{% comment %}
  GENERATED by scripts/generate-liquid-icons.tsx — do not edit by hand.

  The icon set a section may show (lib/page-builder/icons.ts), drawn from lucide
  exactly as components/sections/section-icon.tsx draws it in the Next build —
  same paths, same 24 × 24 grid, the same 1.25 stroke.

  Usage:
    {% render 'sb-section-icon', icon: block.settings.icon, class: 'size-9' %}

  An unknown name or 'none' renders nothing.
{% endcomment %}

{%- liquid
  assign klass = class | default: 'size-6'
  assign known = '${SECTION_ICONS.filter((icon) => icon.value !== "none")
    .map((icon) => icon.value)
    .join(",")}' | split: ','
-%}

{%- if known contains icon -%}
<svg class="{{ klass }}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.25" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">
{%- case icon -%}
${cases.join("\n")}
{%- endcase -%}
</svg>
{%- endif -%}
`;
}

if (require.main === module) {
  const next = iconSnippet();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUT, "utf8");
    } catch {}
    if (current !== next) {
      console.error("✗ theme/snippets/sb-section-icon.liquid is out of date — run: yarn liquid:icons");
      process.exit(1);
    }
    console.log("✓ sb-section-icon.liquid matches the Next icon set");
  } else {
    writeFileSync(OUT, next, "utf8");
    console.log(`wrote ${OUT}`);
  }
}
